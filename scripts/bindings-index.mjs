#!/usr/bin/env node
// Writes src/lib/bindings/index.ts re-exporting every ts-rs generated type.
// Run after `cargo test -p rustcut-model` (npm run bindings does both).
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(resolve(dirname(fileURLToPath(import.meta.url)), ".."), "src", "lib", "bindings");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .sort();
const body = files.map((f) => `export type * from "./${f.replace(/\.ts$/, "")}";`).join("\n");
writeFileSync(
  join(dir, "index.ts"),
  `// GENERATED by scripts/bindings-index.mjs from ts-rs output. Do not edit.\n// Source of truth: crates/rustcut-model (run \`npm run bindings\`).\n${body}\n`,
);
console.log(`✓ bindings index: ${files.length} types`);
